'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const lib=require('./update-master.cjs');
const master=JSON.parse(fs.readFileSync('data/game-master.json','utf8'));
const html=fs.readFileSync('index.html','utf8');
function load(next){
 const window={};
 const sandbox={window};
 for(const path of ['data/game-master.js','data/legacy-ship-baseline.js','data/expedition-rules.js','data/equipment-rules.js'])vm.runInNewContext(fs.readFileSync(path,'utf8'),sandbox);
 if(next)window.KC_MASTER=next;
 const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
 for(const js of scripts)new vm.Script(js);
 vm.runInNewContext(scripts[0],sandbox);
 vm.runInNewContext(scripts[1],sandbox);
 return window;
}
const w=load(),E=w.ExpCalc;
for(const [path,expected] of Object.entries(lib.files(master)))assert.equal(fs.readFileSync(path,'utf8'),expected);
assert.equal(w.EXPEDITIONS.length,w.KC_EXPEDITION_RULES.length);
const exp=w.EXPEDITIONS.find(x=>x.id==='A1'),api=master.expeditions.find(x=>x.id==='A1');
assert.equal(exp.consumptionPct.fuel,api.fuelPct);
const legacy=w.KC_LEGACY_SHIPS.find(x=>x[0]===487);
const ship={shipId:'487',name:legacy[1],stype:legacy[2],fuel:legacy[3],ammo:legacy[4],kira:true};
E.applyShipMaster(ship);
assert.equal(Object.keys(ship.overrides).length,0);
assert.equal('fuel' in ship,false);
assert.equal(ship.kira,true);
assert.equal(E.equipmentTotals({ships:[ship]}).percent,5);
assert.equal(E.equipmentTotals({ships:[{shipId:'289',kinu:true}]}).percent,0);
const custom={shipId:'487',name:'独自艦名',fuel:999,ammo:legacy[4]};
E.applyShipMaster(custom);
assert.equal(custom.overrides.fuel,999);
assert.equal(custom.overrides.name,'独自艦名');
const unknown={shipId:'999999',fuel:10,ammo:20,name:'未知'};
E.applyShipMaster(unknown);
assert.equal(E.shipField(unknown,'fuel'),10);
const next=JSON.parse(JSON.stringify(master));
const row=next.ships.find(x=>x[0]===487);
row[3]+=10;
const updated=load(next).ExpCalc;
assert.equal(updated.shipField(ship,'fuel'),row[3]);
assert.equal(updated.shipCost(ship,50,'fuel'),Math.floor(row[3]/2));
assert.equal(updated.shipField(custom,'fuel'),999);
updated.setShipOverride(custom,'fuel',null);
assert.equal(updated.shipField(custom,'fuel'),row[3]);
assert.ok(lib.guard(master,next,w.KC_EXPEDITION_RULES).ships.changed.includes(487));
const removed=JSON.parse(JSON.stringify(master));removed.ships=removed.ships.filter(x=>x[0]!==487);
assert.throws(()=>lib.guard(master,removed,w.KC_EXPEDITION_RULES));
assert.throws(()=>lib.extract({},master.sourceSha));
assert.equal(E.equipmentMaster(1).id,1);
console.log('Master consistency, runtime resolution, migration, manual overrides, unknown IDs, and update guards: OK');
